import os as _os

GEN = _os.path.dirname(_os.path.abspath(__file__))
SEED = _os.path.dirname(_os.path.dirname(GEN))

"""Write test/check/universal.ts from the library and control files, so the suite checks exactly what they state."""
import re

ROOT = SEED
OUT = _os.path.join(SEED, '..', 'term', 'test/check/universal.ts')


def rules(path):
    text = open(path).read()
    out = {}
    for part in re.split(r'\n(?=rule )', text):
        if part.startswith('rule '):
            name = part.split('\n', 1)[0][5:].strip()
            out[name] = re.split(r'\n\n#', part)[0].rstrip() + '\n'
    return out


lib, ctl = {}, {}
for f in ['code/number/completeness.tree', 'code/integral/fundamental.tree', 'tmp/universal-probe.tree', 'tmp/fn-mark-probe.tree']:
    lib.update(rules(f'{ROOT}/{f}'))
for f in ['test/case/number/completeness-control.tree', 'test/case/number/fundamental-control.tree']:
    ctl.update(rules(f'{ROOT}/{f}'))

CASES = [
    ('a quantified function is a pure application', lib['probe-function-mark'], 'ok'),
    ('x(n) >= 0 does not give x(n + 1) >= 0', lib['probe-function-mark-false'], 'unproven'),
    ('a universal hypothesis chains through two instances', lib['probe-universal-chain'], 'ok'),
    ('and is not read backwards', lib['probe-universal-false'], 'unproven'),
    ('the limit of a Cauchy sequence of reals is a real', lib['the-limit-is-a-real'], 'ok'),
    ('the sequence converges to its limit', lib['the-sequence-converges-to-its-limit'], 'ok'),
    ('a tighter limit is refused', ctl['control-a-tighter-limit'], 'unproven'),
    ('the limit without the Cauchy hypothesis is refused', ctl['control-without-cauchy'], 'unproven'),
    ('a tighter convergence is refused', ctl['control-a-tighter-convergence'], 'unproven'),
    ('the fundamental theorem of calculus, for Riemann sums', lib['the-riemann-sums-of-a-derivative-approach-its-difference'], 'ok'),
    ('the disk area sum telescopes', lib['the-disk-area-sum-telescopes'], 'ok'),
    ('cosh has derivative sinh', lib['cosh-has-derivative-sinh'], 'ok'),
    ('area equals defect (Gauss-Bonnet)', lib['area-equals-defect'], 'ok'),
    ('half the tolerance is refused', ctl['control-half-the-tolerance'], 'unproven'),
    ('the sum without the derivative is refused', ctl['control-without-the-derivative'], 'unproven'),
    ('a nonlinear hypothesis is assumed as stated, never as its negation', ctl['control-a-two-sided-nonlinear-hypothesis'], 'unproven'),
    ('the telescoped sum off by one is refused', ctl['control-the-disk-sum-off-by-one'], 'unproven'),
    ('cosh without the cube term is refused', ctl['control-cosh-without-the-cube'], 'unproven'),
    ('Gauss-Bonnet without the turning identity is refused', ctl['control-gauss-bonnet-without-the-turning'], 'unproven'),
]

HEAD = '''// Quantified FUNCTIONS and UNIVERSAL hypotheses in theorems (check/holds.ts applicationKey, universalGoal,
// universalInduction): a `mark x, like task` is a pure application, a `have h / mark t / P` holds for every t and is
// instantiated at the terms the goal names, and `fold n` inducts over a goal whose recurrences are such hypotheses.
// Every goal is decided over an ordered field. Run: npx tsx test/check/universal.ts
//
// GENERATED by deck/term/deck/seed.tree/tmp/gen/universal-suite.py from the library and control files, so it checks
// exactly what they state: the completeness of the reals, the fundamental theorem of calculus, cosh's derivative and
// Gauss-Bonnet, each refusal beside a statement that must still be proven.

import { compile } from '@term/make/code/compile/compile'

let pass = 0
let fail = 0

function expect(name: string, source: string, want: string): void {
  const result = compile({ file: 's.tree', text: source })
  const codes = result.ok ? [] : result.diagnostics.map(d => d.name)
  const good = want === 'ok' ? result.ok : !result.ok && codes.includes(want)

  if (good) {
    pass++
    console.log(`ok    ${name}`)
  } else {
    fail++
    console.log(`FAIL  ${name}  (ok=${result.ok}, codes=${codes.join(',')}, wanted ${want})`)
  }
}
'''

body = [HEAD]
for name, src, want in CASES:
    body.append('expect(\n  %r,\n  `\n%s`,\n  %r,\n)\n' % (name, src.replace('`', '\\`'), want))
body.append('''console.log(`\\nuniversal: ${pass} pass, ${fail} fail`)

if (fail > 0) {
  process.exit(1)
}
''')
open(OUT, 'w').write('\n'.join(body))
print(len(CASES), 'cases')
